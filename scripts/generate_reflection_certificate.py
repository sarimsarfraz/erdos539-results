#!/usr/bin/env python3
"""Prepare candidate Lean certificates from the captured example.

This script is not trusted verification. Every set identity, count and rational
log inequality in the generated files must pass scripts/check.py and the axiom
audit. Uses Python's standard library only, and never invokes Lean concurrently.
"""
from collections import Counter
from fractions import Fraction as F
from pathlib import Path
import argparse
import json
import re

ROOT = Path(__file__).resolve().parent.parent
parser = argparse.ArgumentParser()
parser.add_argument('--blocks', type=int, default=25)
parser.add_argument('--centers-per-module', type=int, default=4)
parser.add_argument('--energy-chunk-size', type=int, default=16)
args = parser.parse_args()
if not 1 <= args.centers_per_module <= 16 or args.energy_chunk_size < 1:
    parser.error('centers-per-module must be 1..16 and energy-chunk-size must be positive')
S = json.loads((ROOT / 'data/fresh-stationary-energy-fibring-example.json').read_text())['set']
assert len(S) == len(set(S)) == 70
HEADER = '''/-
Copyright 2026 Sarim Sarfraz
SPDX-License-Identifier: Apache-2.0
Generated by scripts/generate_reflection_certificate.py.
All finite certificates below are checked by Lean's kernel.
-/
'''
cumulative = 0
cumulative_energy = 0
for block in range(args.blocks):
    start, end = block * 16, min(387, (block + 1) * 16)
    assert start < end
    s = HEADER
    if block:
        s += f'import Erdos539.ReflectionCertificate{block-1:02d}\n'
    else:
        s += '''import Erdos539.ReflectionCounterexampleSet
import Erdos539.IntegerListCounting
import Erdos539.RationalScaledLogCertificate
import Erdos539.ReflectedIntegerDefect
'''
    s += '\nnamespace Erdos539Geometry\nopen scoped BigOperators\n\n'
    subtotal = 0
    energy_subtotal = 0
    for w in range(start, end):
        T = [a for a in S if w-a in S]
        r = len(T)
        bound = 2 * max(T, default=0) + 1
        energy_subtotal += r*r
        E = sum(v*v for v in Counter(a+b for a in T for b in T).values())
        q, k, l = F(1), 0, 0
        if r:
            q = F(r**3, E)
            while q >= 2:
                q /= 2
                k += 1
            x = (q-1)/(q+1)
            lower = 2*sum((x**(2*i+1)/F(2*i+1) for i in range(4)), F(0)) + k*F(6931,10000)
            l = (lower*10000).__floor__()
        coeff = r*r*l
        subtotal += coeff
        tag=f'{w:03d}'
        literal='['+', '.join(map(str,T))+']'
        energy_proof = 'by decide +kernel'
        # Bound each kernel reduction instead of evaluating the entire energy
        # sum in one call. The emitted equalities are all kernel checked.
        if bound * r * r > 50000:
            counts = Counter(a+b for a in T for b in T)
            chunks, names, proof = [], [], []
            for i, offset in enumerate(range(0, bound, args.energy_chunk_size)):
                length = min(args.energy_chunk_size, bound-offset)
                chunk = f"(List.range' {offset} {length})"
                chunks.append(chunk)
                names.append(f'hpart{i}')
                total = sum(counts[j]**2 for j in range(offset, offset+length))
                proof.append(f'    have hpart{i} : ({chunk}.map (fun j : ℕ ↦ integerListReflectionCount reflectionDigits{tag} (j : ℤ) ^ 2)).sum = {total} := by decide +kernel')
            proof.append(f'    have hr : List.range {bound} = ' + ' ++ '.join(chunks) + ' := by decide +kernel')
            proof += ['    unfold integerListEnergy', '    rw [hr]',
                '    simp only [List.map_append, List.sum_append, ' + ', '.join(names) + ']']
            energy_proof = 'by\n' + '\n'.join(proof)
        s += f'''private def reflectionDigits{tag} : List ℤ := {literal}

set_option maxRecDepth 10000 in
set_option maxHeartbeats 2000000 in
theorem reflectionCounterexample_stats_{tag} :
    (reflectedSupport reflectionCounterexample {w}).card = {r} ∧
      countingEnergy (reflectedSupport reflectionCounterexample {w}) = {E} := by
  have hn : reflectionDigits{tag}.Nodup := by decide +kernel
  have hs : integerReflection reflectionCounterexample {w} = reflectionDigits{tag}.toFinset := by
    decide +kernel
  have hb : ∀ a ∈ reflectionDigits{tag}.toFinset, 0 ≤ a ∧ 2 * a < ({bound} : ℤ) := by
    decide +kernel
  have he : integerListEnergy reflectionDigits{tag} {bound} = {E} := {energy_proof}
  rw [← integerReflection_eq, hs]
  constructor
  · decide +kernel
  · rw [← integerIntervalEnergy_eq_counting _ {bound} hb, ← integerListEnergy_eq hn, he]
    norm_num

theorem reflectionCounterexample_charge_{tag} :
    ({coeff} / 10000 : ℝ) ≤ reflectedCountingCharge reflectionCounterexample {w} := by
  rw [reflectedCountingCharge_eq_of_stats (r := {r}) (E := {E}) reflectionCounterexample_stats_{tag}.1
    (by simpa using reflectionCounterexample_stats_{tag}.2)]
'''
        if r <= 1:
            s += '  norm_num\n\n'
        else:
            s += f'''  have h := rational_scaled_log_lower (q := {q.numerator} / {q.denominator})
    (l := {l} / 10000) (by norm_num) {k} 4
    (by norm_num [rationalLogSeries, Finset.sum_range_succ])
  norm_num at h
  have hm := mul_le_mul_of_nonneg_left h (show (0 : ℝ) ≤ {r} ^ 2 by norm_num)
  norm_num at hm ⊢
  exact hm

'''
    s += f'''theorem reflectionCounterexample_block_{block:02d} :
    ({subtotal} / 10000 : ℝ) ≤
      ∑ j ∈ Finset.range {end-start}, reflectedCountingCharge reflectionCounterexample (({start} + j : ℕ) : ℤ) := by
'''
    for w in range(start,end):
        s+=f'  have h{w} := reflectionCounterexample_charge_{w:03d}\n'
    s += '  norm_num [Finset.sum_range_succ]\n  linarith\n\n'
    before=cumulative
    cumulative += subtotal
    s += f'''theorem reflectionCounterexample_cumulative_{block:02d} :
    ({cumulative} / 10000 : ℝ) ≤
      ∑ j ∈ Finset.range {end}, reflectedCountingCharge reflectionCounterexample j := by
'''
    if block==0:
        s += f'  simpa using reflectionCounterexample_block_{block:02d}\n'
    else:
        s += f'''  rw [show {end} = {start} + {end-start} by decide, Finset.sum_range_add]
  have h := add_le_add reflectionCounterexample_cumulative_{block-1:02d}
    reflectionCounterexample_block_{block:02d}
  norm_num at h ⊢
  exact h
'''
    s += f"""

theorem reflectionCounterexample_energy_block_{block:02d} :
    (∑ j ∈ Finset.range {end-start},
      ((reflectedSupport reflectionCounterexample (({start} + j : ℕ) : ℤ)).card : ℝ) ^ 2) =
        {energy_subtotal} := by
  norm_num [Finset.sum_range_succ,
"""
    s += ',\n'.join(f'    reflectionCounterexample_stats_{w:03d}.1' for w in range(start,end)) + ']\n'
    cumulative_energy += energy_subtotal
    s += f"""
theorem reflectionCounterexample_energy_cumulative_{block:02d} :
    (∑ j ∈ Finset.range {end},
      ((reflectedSupport reflectionCounterexample (j : ℤ)).card : ℝ) ^ 2) =
        {cumulative_energy} := by
"""
    if block == 0:
        s += f'  simpa using reflectionCounterexample_energy_block_{block:02d}\n'
    else:
        s += f"""  rw [show {end} = {start} + {end-start} by decide, Finset.sum_range_add,
    reflectionCounterexample_energy_cumulative_{block-1:02d}, reflectionCounterexample_energy_block_{block:02d}]
  norm_num
"""
    s += '\nend Erdos539Geometry\n'
    path=ROOT / f'Erdos539/ReflectionCertificate{block:02d}.lean'
    # Keep the public block/cumulative theorem names and statements unchanged.
    # Small imported parts prevent accumulation of elaboration state in one file.
    first = s.index('private def reflectionDigits')
    aggregate = s.index(f'theorem reflectionCounterexample_block_{block:02d}')
    body = s[first:aggregate]
    starts = [m.start() for m in re.finditer(r'^private def reflectionDigits', body, re.M)] + [len(body)]
    pieces = [body[starts[i]:starts[i+1]] for i in range(len(starts)-1)]
    part_dir = path.with_suffix('')
    part_dir.mkdir(exist_ok=True)
    prior_imports = s[len(HEADER):s.index('\nnamespace Erdos539Geometry')]
    namespace = '\nnamespace Erdos539Geometry\nopen scoped BigOperators\n\n'
    last_module = None
    for part, offset in enumerate(range(0, len(pieces), args.centers_per_module)):
        module = f'Erdos539.ReflectionCertificate{block:02d}.Part{part:02d}'
        imports = prior_imports if last_module is None else f'import {last_module}\n'
        (part_dir / f'Part{part:02d}.lean').write_text(HEADER + imports + namespace +
            ''.join(pieces[offset:offset+args.centers_per_module]) + '\nend Erdos539Geometry\n')
        last_module = module
    path.write_text(HEADER + f'import {last_module}\n' + namespace + s[aggregate:])
    print(f'{path.name}: centers {start}-{end-1}, cumulative lower numerator {cumulative}')
